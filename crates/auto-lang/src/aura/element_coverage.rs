/// 单元素查询（tag 精确匹配；归一由调用方处理——coverage.rs normalize_kind）。
pub fn element_status(tag: &str) -> Option<QueueStatus> {
    element_table().iter().find(|(t, _)| *t == tag).map(|(_, s)| *s)
}

/// 覆盖率数字（T6 门禁输出用）：`(covered, not_yet, not_consumed, total)`。
pub fn element_counts() -> (usize, usize, usize, usize) {
    let mut c = (0, 0, 0, 0);
    for (_, s) in element_table() {
        c.3 += 1;
        match s {
            QueueStatus::Covered => c.0 += 1,
            QueueStatus::NotYet(_) => c.1 += 1,
            QueueStatus::NotConsumed(_) => c.2 += 1,
        }
    }
    c
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 表完整性：tag 唯一（生成器语义的手工维护防线）。
    #[test]
    fn element_table_tags_unique() {
        let mut seen = std::collections::BTreeSet::new();
        for (tag, _) in element_table() {
            assert!(seen.insert(*tag), "重复登记: {tag}");
        }
    }

    /// 计数口径：三元计数和 = 总数（覆盖率输出的一致性钉）。
    #[test]
    fn element_counts_add_up() {
        let (c, ny, nc, total) = element_counts();
        assert_eq!(c + ny + nc, total);
        assert!(c > 0, "500 基线元素在表");
    }
}
