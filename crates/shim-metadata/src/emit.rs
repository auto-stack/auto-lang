//! 生成器:MarshalPlan → shim Rust 源码。
//! v1 输出"std 追加段":与 vm/ffi/stdlib.rs 手写臂同构的 match 臂函数,
//! 由 dispatch 3000 在手写臂之前优先调用(Phase D 接线)。

use crate::types::*;

pub fn emit_std_append_segment(plans: &[MarshalPlan]) -> String {
    let mut out = String::new();
    out.push_str("// Generated by shim-metadata (plan-430). DO NOT EDIT BY HAND.\n");
    out.push_str("// std shim append segment: called before the hand-written dispatch arms.\n");
    out.push_str("#[allow(clippy::all)]\n");
    out.push_str("pub fn generated_std_dispatch(\n");
    out.push_str("    type_name: &str,\n    method: &str,\n");
    out.push_str("    task: &mut crate::vm::task::AutoTask,\n    vm: &crate::vm::engine::AutoVM,\n");
    out.push_str(") -> Option<Result<(), crate::vm::error::VMError>> {\n");
    out.push_str("    use crate::vm::ffi::rust_stdlib::RustStdlibObject;\n");
    out.push_str("    use crate::vm::ffi::stdlib::{pop_rust_obj, push_rust_obj};\n");
    out.push_str("    match (type_name, method) {\n");
    for p in plans {
        out.push_str(&emit_arm(p));
    }
    out.push_str("        _ => None,\n    }\n}\n");
    out
}

fn emit_arm(p: &MarshalPlan) -> String {
    let m = &p.method;
    let ty = &m.type_name;
    let name = &m.method;
    let rust_ty = rust_recv_type(ty);
    // 参数弹出(逆序):对每个参数生成 pop 语句。
    let mut pops = String::new();
    let mut argnames = Vec::new();
    for (i, a) in p.args.iter().enumerate() {
        let nm = format!("a{i}");
        argnames.push(nm.clone());
        pops.push_str(&format!(
            "        let {nm}: {t} = {pop}\n            .map_err(|e| crate::vm::error::VMError::RuntimeError(format!(\"{ty}.{name}: {{e}}\")))?;\n",
            nm = nm,
            t = arg_rust_type(a),
            pop = arg_pop_expr(a),
            ty = ty,
            name = name,
        ));
    }
    // self 处理
    let (selfline, recv) = match m.self_kind {
        SelfKind::Static => (String::new(), format!("{rust_ty}::")),
        SelfKind::Read | SelfKind::Write => {
            let mut s = String::new();
            if m.self_kind == SelfKind::Read {
                s.push_str(&format!(
                    "        let handle = task.ram.pop_i32() as u64;\n        let obj = vm.get_heap_object(handle)?;\n        let guard = obj.read().unwrap();\n        let recv: &{rust_ty} = guard.as_any().downcast_ref::<RustStdlibObject>()?.downcast_ref::<{rust_ty}>()?;\n"
                ));
            } else {
                s.push_str(&format!(
                    "        let handle = task.ram.pop_i32() as u64;\n        let obj = vm.get_heap_object(handle)?;\n        let mut guard = obj.write().unwrap();\n        let recv: &mut {rust_ty} = guard.as_any_mut().downcast_mut::<RustStdlibObject>()?.downcast_mut::<{rust_ty}>()?;\n"
                ));
            }
            (s, String::new())
        }
    };
    // 调用 + 返回值压栈
    let call = format!("        let __r = {recv}{name}({args});\n", args = argnames.join(", "));
    let push = match &p.ret {
        RetPlan::Void => format!("        task.ram.push_i32(0);\n"),
        RetPlan::ScalarI32 => format!("        task.ram.push_i32(__r as i32);\n"),
        RetPlan::ScalarI64 => format!("        task.ram.push_i64(__r as i64);\n"),
        RetPlan::ScalarF64 => format!("        task.ram.push_f64(__r as f64);\n"),
        RetPlan::ScalarBool => format!("        task.ram.push_nv(auto_val::encode_bool(__r));\n"),
        RetPlan::ScalarStr => format!(
            "        let idx = vm.add_string(__r.into_bytes());\n        vm.rc_push_str_idx(task, idx as usize);\n"
        ),
        RetPlan::ChainSelf => format!(
            "        drop(__r);\n        task.ram.push_i32(handle as i32);\n"
        ),
        RetPlan::Opaque(t) => format!(
            "        crate::vm::ffi::stdlib::push_rust_obj(task, vm, \"{t}\", __r)?;\n"
        ),
    };
    format!(
        "        (\"{ty}\", \"{name}\") => {{\n{pops}{selfline}{call}{push}            Some(Ok(()))\n        }}\n"
    )
}

fn rust_recv_type(ty: &str) -> String {
    match ty {
        "String" => "String".into(),
        "Vec" => "Vec<auto_val::AutoStr>".into(), // v1:元素按 AutoStr 句柄串,Phase E 校准
        "HashMap" => "std::collections::HashMap<String, i64>".into(),
        "HashSet" => "std::collections::HashSet<String>".into(),
        other => other.into(),
    }
}

fn arg_rust_type(a: &ArgPlan) -> &'static str {
    match a {
        ArgPlan::BorrowStr | ArgPlan::TakeStr => "String",
        ArgPlan::ScalarI32 => "i32",
        ArgPlan::ScalarI64 => "i64",
        ArgPlan::ScalarF64 => "f64",
        ArgPlan::ScalarBool => "bool",
        ArgPlan::SelfHandle | ArgPlan::OpaqueHandle => "i32",
    }
}

fn arg_pop_expr(a: &ArgPlan) -> &'static str {
    match a {
        ArgPlan::BorrowStr | ArgPlan::TakeStr => "String::pop_from_stack(task, vm)",
        ArgPlan::ScalarI32 => "i32::pop_from_stack(task, vm)",
        ArgPlan::ScalarI64 => "i64::pop_from_stack(task, vm)",
        ArgPlan::ScalarF64 => "f64::pop_from_stack(task, vm)",
        ArgPlan::ScalarBool => "Ok(task.ram.pop_i32() != 0)",
        ArgPlan::SelfHandle | ArgPlan::OpaqueHandle => "Ok(task.ram.pop_i32())",
    }
}
