//! Full emit file-set assembly (plan §5.3): `generated.rs` + the minimal
//! typed runtime `a2x_runtime.rs` + the explicit entry wrapper `main.rs` +
//! a deterministic `manifest.json` binding the set by content hashes.
//!
//! Frozen v1 shape (T-02): four files, sibling layout, compiled with
//! `rustc --edition 2021 main.rs` (`mod` declarations resolve siblings).
//! Observation protocol of the wrapper (value/trap channels never mix):
//! * stdout: exactly one line — `value:<i32>` or `trap:<Name>`;
//! * stderr: one line per executed trace mark, in execution order
//!   (`mark_a`/`mark_b`), emitted at mark time (marks before a trap stay
//!   observable);
//! * process exit code 0 whenever the wrapper observed the outcome;
//!   a non-zero exit is infrastructure, never a language verdict.
//! Trace mark return values follow the frozen native contract
//! (ac-core `test-support/marks.rs`): mark_a → 1, mark_b → 2.

use crate::lower::RustProgram;
use crate::print::print_program;
use crate::target::TargetProfile;
use auto_a2x_core::{sha256::sha256_hex, SemanticView};

pub const FILESET_SCHEMA: &str = "auto.a2x.rust.fileset/1";

/// An assembled file set: relative paths → contents, plus the manifest
/// describing them (the manifest itself is not a member of its own file
/// list).
pub struct FileSet {
    pub files: Vec<(String, String)>,
    pub manifest: String,
}

/// Assemble the complete file set for a lowered program.
pub fn assemble_file_set(
    view: &SemanticView<'_>,
    program: &RustProgram,
    input_hash: &str,
    entry_source_name: &str,
) -> FileSet {
    let target = TargetProfile::v1();

    let mut generated = String::new();
    generated.push_str(&format!(
        "// AUTO-GENERATED by {} v{} (PLAN-892 AX-A) — DO NOT EDIT.\n\
         // source profile: {} | hir domain: {} | input hash (fnv1a-64): {}\n\
         // entry: `{}` -> `{}`\n\n",
        target.backend,
        target.backend_version,
        view.profile,
        view.domain.as_str(),
        input_hash,
        entry_source_name,
        program.entry
    ));
    generated.push_str("use crate::a2x_runtime::*;\n\n");
    generated.push_str(&print_program(program));

    let runtime = runtime_source(&program.marks);

    let mut wrapper = String::new();
    wrapper.push_str(&format!(
        "// AUTO-GENERATED by {} v{} (PLAN-892 AX-A) — DO NOT EDIT.\n",
        target.backend, target.backend_version
    ));
    wrapper.push_str("mod a2x_runtime;\nmod generated;\n\n");
    wrapper.push_str("use a2x_runtime::A2xResult;\n\n");
    wrapper.push_str("fn main() {\n");
    wrapper.push_str(&format!(
        "    let outcome: A2xResult<i32> = generated::{}();\n",
        program.entry
    ));
    wrapper.push_str("    match outcome {\n");
    wrapper.push_str("        Ok(v) => println!(\"value:{}\", v),\n");
    wrapper.push_str("        Err(t) => println!(\"trap:{}\", t.name()),\n");
    wrapper.push_str("    }\n}\n");

    let files = vec![
        ("main.rs".to_string(), wrapper),
        ("a2x_runtime.rs".to_string(), runtime),
        ("generated.rs".to_string(), generated),
    ];
    let manifest = build_manifest(
        &files,
        view,
        input_hash,
        entry_source_name,
        program,
        &target,
    );
    FileSet { files, manifest }
}

fn build_manifest(
    files: &[(String, String)],
    view: &SemanticView<'_>,
    input_hash: &str,
    entry_source_name: &str,
    program: &RustProgram,
    target: &TargetProfile,
) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str(&format!("  \"schema\": \"{}\",\n", FILESET_SCHEMA));
    out.push_str(&format!("  \"source_profile\": \"{}\",\n", view.profile));
    out.push_str(&format!(
        "  \"hir_domain\": \"{}\",\n",
        view.domain.as_str()
    ));
    out.push_str(&format!("  \"input_hash\": \"{}\",\n", input_hash));
    out.push_str(&format!("  \"entry\": \"{}\",\n", entry_source_name));
    out.push_str(&format!("  \"entry_fn\": \"{}\",\n", program.entry));
    out.push_str(&format!(
        "  \"target\": {{ \"lang\": \"{}\", \"edition\": \"{}\", \"backend\": \"{}\", \"backend_version\": \"{}\" }},\n",
        target.lang, target.edition, target.backend, target.backend_version
    ));
    out.push_str("  \"files\": [\n");
    for (i, (path, content)) in files.iter().enumerate() {
        let comma = if i + 1 < files.len() { "," } else { "" };
        out.push_str(&format!(
            "    {{ \"path\": \"{}\", \"sha256\": \"{}\" }}{}\n",
            path,
            sha256_hex(content.as_bytes()),
            comma
        ));
    }
    out.push_str("  ]\n");
    out.push_str("}\n");
    out
}

/// The minimal typed runtime (plan §5.1: "标量helper只实现typed原语/授权trace，
/// 不接收AST/MIR/ABC执行指令"). `#![allow(dead_code)]` because a given emit
/// uses a subset of the primitive set.
fn runtime_source(marks: &[&'static str]) -> String {
    let mut s = String::new();
    s.push_str("// AUTO-GENERATED minimal typed runtime (PLAN-892 AX-A) — DO NOT EDIT.\n");
    s.push_str("// Checked i32 primitives with named traps + authorized trace marks.\n");
    s.push_str("#![allow(dead_code)]\n\n");
    s.push_str(
        "/// Named Auto trap reasons (plan §5.1): add/sub/mul/neg overflow,\n\
         /// division/remainder by zero, MIN/-1 division and MIN%-1 remainder.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub enum AutoTrap { Overflow, DivByZero, DivOverflow, RemByZero, RemOverflow }\n\n\
         impl AutoTrap {\n\
         \x20   pub fn name(self) -> &'static str {\n\
         \x20       match self {\n\
         \x20           AutoTrap::Overflow => \"Overflow\",\n\
         \x20           AutoTrap::DivByZero => \"DivByZero\",\n\
         \x20           AutoTrap::DivOverflow => \"DivOverflow\",\n\
         \x20           AutoTrap::RemByZero => \"RemByZero\",\n\
         \x20           AutoTrap::RemOverflow => \"RemOverflow\",\n\
         \x20       }\n\
         \x20   }\n\
         }\n\n\
         pub type A2xResult<T> = Result<T, AutoTrap>;\n\n\
         pub fn a2x_add(a: i32, b: i32) -> A2xResult<i32> { a.checked_add(b).ok_or(AutoTrap::Overflow) }\n\
         pub fn a2x_sub(a: i32, b: i32) -> A2xResult<i32> { a.checked_sub(b).ok_or(AutoTrap::Overflow) }\n\
         pub fn a2x_mul(a: i32, b: i32) -> A2xResult<i32> { a.checked_mul(b).ok_or(AutoTrap::Overflow) }\n\
         pub fn a2x_neg(a: i32) -> A2xResult<i32> { a.checked_neg().ok_or(AutoTrap::Overflow) }\n\
         pub fn a2x_div(a: i32, b: i32) -> A2xResult<i32> {\n\
         \x20   if b == 0 { Err(AutoTrap::DivByZero) } else { a.checked_div(b).ok_or(AutoTrap::DivOverflow) }\n\
         }\n\
         pub fn a2x_rem(a: i32, b: i32) -> A2xResult<i32> {\n\
         \x20   if b == 0 { Err(AutoTrap::RemByZero) } else { a.checked_rem(b).ok_or(AutoTrap::RemOverflow) }\n\
         }\n",
    );
    for &mark in marks {
        let (suffix, value) = if mark == "hir.test.mark_a" {
            ("a", "1")
        } else {
            ("b", "2")
        };
        s.push_str(&format!(
            "\npub fn a2x_mark_{suf}() -> i32 {{\n\
             \x20   eprintln!(\"mark_{suf}\");\n\
             \x20   {val}\n\
             }}\n",
            suf = suffix,
            val = value
        ));
    }
    s
}
