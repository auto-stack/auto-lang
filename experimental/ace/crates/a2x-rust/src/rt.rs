//! PLAN-902 record/text emit file-set assembly: the typed RESOURCE runtime
//! (`a2x_runtime.rs` v2 for the record-text recipe) + `generated.rs` +
//! `main.rs` wrapper + deterministic manifest, schema
//! `auto.a2x.rust.record-text.fileset/1`.
//!
//! Frozen shape (T-02): four files, sibling layout, compiled with
//! `rustc --edition 2021 main.rs`. Observation protocol of the wrapper is
//! the frozen `a2xworker/1` one (stdout `value:<i32>`/`trap:<Name>`,
//! stderr marks, exit 0 = observed).
//!
//! Resource contract (plan §5.3):
//! * owned `Str` is the runtime type `A2xStr`; buffers are freed ONLY by
//!   the explicit `a2x_str_free` calls the lowering emits at the
//!   verifier-scheduled points — plain lexical Drop is never relied on
//!   (the runtime type has no Drop);
//! * allocation budgets are CHECKED BEFORE every allocation (try_reserve,
//!   checked length arithmetic); host allocation failure is the typed
//!   `Resource` trap, never a panic;
//! * `len` counts Unicode scalars, `len_bytes` UTF-8 bytes, `eq/ne`
//!   compare full bytes with no normalization (NUL included);
//! * a TEST-ONLY, default-off fault/observation configuration arrives via
//!   environment variables read lazily by the runtime itself — the emitted
//!   file set is identical in daily and certified runs:
//!   `A2X_RT_FAULT_ALLOC=<n>` fails the n-th allocation (typed Resource),
//!   `A2X_RT_EVENTS=1` mirrors alloc/free events to stderr as
//!   `rt:alloc:<bytes>` / `rt:free:<bytes>` lines.

use crate::lower::RustProgram;
use crate::print::print_program;
use crate::target::TargetProfile;
use ace_a2x_core::{sha256::sha256_hex, SemanticView};

pub const RT_FILESET_SCHEMA: &str = "auto.a2x.rust.record-text.fileset/1";

/// An assembled file set: relative paths → contents, plus the manifest
/// describing them (the manifest itself is not a member of its own file
/// list).
pub struct RtFileSet {
    pub files: Vec<(String, String)>,
    pub manifest: String,
}

/// Assemble the complete record-text file set for a lowered program.
pub fn assemble_record_text_file_set(
    view: &SemanticView<'_>,
    program: &RustProgram,
    input_hash: &str,
    entry_source_name: &str,
) -> RtFileSet {
    let target = TargetProfile::v1();

    let mut generated = String::new();
    generated.push_str(&format!(
        "// AUTO-GENERATED by {} v{} (PLAN-902 AX-B) — DO NOT EDIT.\n\
         // source profile: {} | hir domain: {} | input hash (fnv1a-64): {}\n\
         // entry: `{}` -> `{}`\n\n",
        target.backend,
        target.backend_version,
        view.profile,
        view.domain.as_str(),
        input_hash,
        entry_source_name,
        program.entry
    ));
    generated.push_str("use crate::a2x_runtime::*;\n\n");
    generated.push_str(&print_program(program));

    let runtime = record_text_runtime_source(&program.marks);

    let mut wrapper = String::new();
    wrapper.push_str(&format!(
        "// AUTO-GENERATED by {} v{} (PLAN-902 AX-B) — DO NOT EDIT.\n",
        target.backend, target.backend_version
    ));
    wrapper.push_str("mod a2x_runtime;\nmod generated;\n\n");
    wrapper.push_str("use a2x_runtime::A2xResult;\n\n");
    wrapper.push_str("fn main() {\n");
    wrapper.push_str(&format!(
        "    let outcome: A2xResult<i32> = generated::{}();\n",
        program.entry
    ));
    wrapper.push_str("    match outcome {\n");
    wrapper.push_str("        Ok(v) => println!(\"value:{}\", v),\n");
    wrapper.push_str("        Err(t) => println!(\"trap:{}\", t.name()),\n");
    wrapper.push_str("    }\n}\n");

    let files = vec![
        ("main.rs".to_string(), wrapper),
        ("a2x_runtime.rs".to_string(), runtime),
        ("generated.rs".to_string(), generated),
    ];
    let manifest = build_rt_manifest(
        &files,
        view,
        input_hash,
        entry_source_name,
        program,
        &target,
    );
    RtFileSet { files, manifest }
}

fn build_rt_manifest(
    files: &[(String, String)],
    view: &SemanticView<'_>,
    input_hash: &str,
    entry_source_name: &str,
    program: &RustProgram,
    target: &TargetProfile,
) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str(&format!("  \"schema\": \"{}\",\n", RT_FILESET_SCHEMA));
    out.push_str(&format!("  \"source_profile\": \"{}\",\n", view.profile));
    out.push_str(&format!(
        "  \"hir_domain\": \"{}\",\n",
        view.domain.as_str()
    ));
    out.push_str(&format!("  \"input_hash\": \"{}\",\n", input_hash));
    out.push_str(&format!("  \"entry\": \"{}\",\n", entry_source_name));
    out.push_str(&format!("  \"entry_fn\": \"{}\",\n", program.entry));
    out.push_str(&format!(
        "  \"target\": {{ \"lang\": \"{}\", \"edition\": \"{}\", \"backend\": \"{}\", \"backend_version\": \"{}\", \"resource_runtime\": \"a2x-rt/1\" }},\n",
        target.lang, target.edition, target.backend, target.backend_version
    ));
    out.push_str("  \"files\": [\n");
    for (i, (path, content)) in files.iter().enumerate() {
        let comma = if i + 1 < files.len() { "," } else { "" };
        out.push_str(&format!(
            "    {{ \"path\": \"{}\", \"sha256\": \"{}\" }}{}\n",
            path,
            sha256_hex(content.as_bytes()),
            comma
        ));
    }
    out.push_str("  ]\n");
    out.push_str("}\n");
    out
}

/// The typed resource runtime for the record-text recipe: the frozen
/// scalar checked-i32 core + the PLAN-902 text/resource layer. The emitted
/// text is IDENTICAL for daily and certified runs; the fault/observation
/// knobs live in the (lazy, default-off) environment configuration.
pub fn record_text_runtime_source(marks: &[&'static str]) -> String {
    let mut s = String::new();
    s.push_str("// AUTO-GENERATED typed resource runtime (PLAN-902 AX-B) — DO NOT EDIT.\n");
    s.push_str("// Checked i32 core + owned-Str resource layer with explicit cleanup,\n");
    s.push_str("// pre-allocation budget checks and default-off fault/observation hooks.\n");
    s.push_str("#![allow(dead_code)]\n\n");
    s.push_str(RT_CORE);
    for &mark in marks {
        let (suffix, value) = if mark == "hir.test.mark_a" {
            ("a", "1")
        } else {
            ("b", "2")
        };
        s.push_str(&format!(
            "\npub fn a2x_mark_{suf}() -> i32 {{\n\
             \x20   eprintln!(\"mark_{suf}\");\n\
             \x20   {val}\n\
             }}\n",
            suf = suffix,
            val = value
        ));
    }
    s
}

