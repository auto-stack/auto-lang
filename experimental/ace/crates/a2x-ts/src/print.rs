//! PLAN-976: deterministic whole-program script printer and line source-map
//! generator, shared by the TypeScript and JavaScript legs.

use ace_a2x_core::{A2xReject, FragmentText};

use crate::lower::{sanitize, ts_fn_name, ts_method_name};
use crate::runtime::runtime_export_names;
use crate::target::ScriptLang;

/// Version tag of the script source printer format.
pub const TS_PRINT_VERSION: &str = "a2ts-print/1";

/// One source-map entry linking an Auto declaration + origin span to exact
/// 1-based line numbers inside the generated module.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SourceMapEntry {
    pub decl: String,
    pub decl_kind: String,
    pub origin_start: u32,
    pub origin_end: u32,
    pub gen_line_start: usize,
    pub gen_line_end: usize,
}

/// Output bundle of [`print_program`].
#[derive(Clone, Debug)]
pub struct PrintedProgram {
    pub generated: String,
    pub main: String,
    pub source_map: Vec<SourceMapEntry>,
    pub source_map_json: String,
}

fn parse_origin_header(line: &str) -> Option<(u32, u32)> {
    let rest = line.strip_prefix("// origin: ")?;
    let span_part = rest.split_whitespace().next()?;
    let (s, e) = span_part.split_once("..")?;
    Some((s.parse().ok()?, e.parse().ok()?))
}

fn json_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out
}

fn entry_symbol(entry: &str) -> String {
    ts_fn_name(entry)
}

/// True when `text` references the identifier `name` at a word boundary.
fn uses_ident(text: &str, name: &str) -> bool {
    let bytes = text.as_bytes();
    let nb = name.as_bytes();
    let mut start = 0usize;
    while let Some(pos) = text[start..].find(name) {
        let at = start + pos;
        let before_ok =
            at == 0 || !(bytes[at - 1].is_ascii_alphanumeric() || bytes[at - 1] == b'_');
        let end = at + nb.len();
        let after_ok =
            end >= bytes.len() || !(bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_');
        if before_ok && after_ok {
            return true;
        }
        start = at + 1;
    }
    false
}

fn import_list(prelude: &str, fragments: &[FragmentText<'_>]) -> Vec<String> {
    let mut all = String::with_capacity(prelude.len() + 4096);
    all.push_str(prelude);
    for f in fragments {
        all.push_str(&f.text);
        all.push('\n');
    }
    runtime_export_names()
        .iter()
        .filter(|n| uses_ident(&all, n))
        .map(|n| (*n).to_string())
        .collect()
}

/// Print `generated.<ts|mjs>`, `a2x_main.<ts|mjs>` and `source_map.json`
/// deterministically from cached or freshly lowered fragments plus the
/// optional seed-rendered prelude helpers.
pub fn print_program(
    lang: ScriptLang,
    prelude_helpers: &str,
    fragments: &[FragmentText<'_>],
    entry: &str,
    origins: Option<&[(usize, (u32, u32))]>,
    schema: &str,
    input_hash: &str,
) -> Result<PrintedProgram, A2xReject> {
    let symbol = entry_symbol(entry);

    let mut generated = String::new();
    generated.push_str(&format!(
        "// AUTO-GENERATED BY {TS_PRINT_VERSION} ({schema}) — DO NOT EDIT.\n\
         // input_hash: {input_hash}\n"
    ));
    let imports = import_list(prelude_helpers, fragments);
    if !imports.is_empty() {
        generated.push_str(&format!(
            "import {{ {} }} from \"./a2x_rt.mjs\";\n",
            imports.join(", ")
        ));
    }
    generated.push('\n');

    if !prelude_helpers.is_empty() {
        generated.push_str(prelude_helpers);
        if !prelude_helpers.ends_with('\n') {
            generated.push('\n');
        }
    }

    let mut cur_line = generated.lines().count() + 1;
    let mut source_map = Vec::with_capacity(fragments.len());

    for frag in fragments {
        let trimmed = frag.text.trim_end_matches('\n');
        let line_count = trimmed.lines().count().max(1);
        let parsed_origin = frag.text.lines().next().and_then(parse_origin_header);
        let fallback_origin = origins
            .and_then(|o| o.iter().find(|(d, _)| *d == frag.def_index))
            .map(|o| o.1)
            .unwrap_or((0, 0));
        let (origin_start, origin_end) = parsed_origin.unwrap_or(fallback_origin);

        let method_name = ts_method_name(&frag.source_name);
        let decl_kind = if trimmed.contains(&format!("function {method_name}(")) {
            "method"
        } else {
            "fn"
        };

        let gen_line_start = cur_line;
        let gen_line_end = cur_line + line_count - 1;
        source_map.push(SourceMapEntry {
            decl: frag.source_name.to_string(),
            decl_kind: decl_kind.to_string(),
            origin_start,
            origin_end,
            gen_line_start,
            gen_line_end,
        });

        generated.push_str(trimmed);
        generated.push_str("\n\n");
        cur_line = gen_line_end + 2;
    }

    let ext = lang.source_ext();
    let main = match lang {
        ScriptLang::TypeScript => format!(
            "// AUTO-GENERATED BY {TS_PRINT_VERSION} ({schema}) — DO NOT EDIT.\n\
             declare const process: {{ exitCode?: number }};\n\
             import {{ a2x_run_main }} from \"./a2x_rt.mjs\";\n\
             import * as generated from \"./generated.ts\";\n\n\
             process.exitCode = a2x_run_main(generated.{symbol});\n"
        ),
        ScriptLang::JavaScript => format!(
            "// AUTO-GENERATED BY {TS_PRINT_VERSION} ({schema}) — DO NOT EDIT.\n\
             import {{ a2x_run_main }} from \"./a2x_rt.mjs\";\n\
             import * as generated from \"./generated.{ext}\";\n\n\
             process.exitCode = a2x_run_main(generated.{symbol});\n"
        ),
    };

    let mut sm = String::from("{\n  \"version\": \"");
    sm.push_str(TS_PRINT_VERSION);
    sm.push_str("\",\n  \"entry\": \"");
    sm.push_str(&json_escape(entry));
    sm.push_str("\",\n  \"entries\": [\n");
    for (idx, item) in source_map.iter().enumerate() {
        let comma = if idx + 1 < source_map.len() { "," } else { "" };
        sm.push_str(&format!(
            "    {{ \"decl\": \"{}\", \"decl_kind\": \"{}\", \"origin\": [{}, {}], \"generated_lines\": [{}, {}] }}{}\n",
            json_escape(&item.decl),
            json_escape(&item.decl_kind),
            item.origin_start,
            item.origin_end,
            item.gen_line_start,
            item.gen_line_end,
            comma
        ));
    }
    sm.push_str("  ]\n}\n");

    Ok(PrintedProgram {
        generated,
        main,
        source_map,
        source_map_json: sm,
    })
}

/// Deterministic sanitizer re-export used by assembly-time diagnostics.
pub fn sanitized(s: &str) -> String {
    sanitize(s)
}
