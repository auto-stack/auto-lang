/// Build the emitted runtime source for one language.
///
/// The body is the single source of truth for the helper catalogue and for the
/// `hir.test.mark_a` / `hir.test.mark_b` helpers (which it always exports; only
/// the printer's import/call list is view-gated). The emitter injects the
/// identity of the *emitted* file through `globalThis` values read by the body
/// at module evaluation, so the body is never re-declaring those names.
pub fn script_runtime_body(lang: ScriptLang, marks: &[&'static str]) -> String {
    // `marks` documents which trace helpers the view authorises; the body
    // exports both unconditionally and unused ones are never imported.
    let _ = marks;
    let mut out = String::with_capacity(RUNTIME_BODY.len() + 512);
    out.push_str("// AUTO-GENERATED by auto-a2x-ts (PLAN-976) -- DO NOT EDIT.\n");
    out.push_str(&format!(
        "globalThis.__a2ts_runtime_version = {:?};\n",
        A2TS_RUNTIME_VERSION
    ));
    out.push_str(&format!(
        "globalThis.__a2ts_runtime_body_sha256 = {:?};\n",
        sha256_hex(RUNTIME_BODY.as_bytes())
    ));
    out.push_str(&format!(
        "globalThis.__a2ts_target_lang = {:?};\n",
        lang.lang_name()
    ));
    out.push_str(RUNTIME_BODY);
    out
}

/// Embed an isolated copy of the JavaScript runtime inside a widget factory.
/// Each factory owns its text ledger and publishes no runtime globals.
pub fn script_widget_runtime_body() -> String {
    use std::fmt::Write;

    let mut out = String::with_capacity(RUNTIME_BODY.len() + 1024);
    writeln!(out, "const _widgetRuntimeIdentity = {{ __a2ts_runtime_version: {:?}, __a2ts_runtime_body_sha256: {:?}, __a2ts_target_lang: \"javascript\" }};",
        A2TS_RUNTIME_VERSION, sha256_hex(RUNTIME_BODY.as_bytes())).unwrap();
    for line in RUNTIME_BODY.lines() {
        match line {
            "globalThis.__a2ts_rt = _RT;" => continue,
            "    const g = globalThis;" => out.push_str("    const g = _widgetRuntimeIdentity;"),
            _ => out.push_str(line.strip_prefix("export ").unwrap_or(line)),
        }
        out.push('\n');
    }
    out.push_str(include_str!("widget_scope.js"));
    out.push_str(include_str!("widget_json.js"));
    out
}

/// The declaration file for the TypeScript leg (the body is plain JS).
pub fn script_runtime_declaration() -> String {
    let mut out = String::with_capacity(RUNTIME_DECLARATION.len() + 256);
    out.push_str("// AUTO-GENERATED by auto-a2x-ts (PLAN-976) -- DO NOT EDIT.\n");
    out.push_str(RUNTIME_DECLARATION);
    out
}
