//! PLAN-976: the versioned script runtime (`a2x_rt.mjs` + `a2x_rt.d.mts`).
//!
//! The runtime text is versioned and its content hash participates in every
//! fragment key, so a runtime change invalidates all emitted fragments instead
//! of silently pairing old fragments with new helpers.

use ace_core::runtime_contract::sha256_hex;

use crate::target::ScriptLang;

/// Version tag of the script runtime module.
pub const A2TS_RUNTIME_VERSION: &str = "a2ts-runtime/1";

/// The runtime body (plain ESM JavaScript) exactly as emitted.
pub const RUNTIME_BODY: &str = include_str!("rt_body.js");

/// The TypeScript declaration accompanying the runtime.
pub const RUNTIME_DECLARATION: &str = include_str!("rt_decl.d.mts");

/// The `version@sha256` dependency token the emitted port calls pass to the
/// runtime (validated by `a2x_port_call`; never re-computed at runtime).
pub fn port_catalog_dep() -> String {
    format!("{}@{}", A2TS_RUNTIME_VERSION, runtime_body_sha256())
}

/// Fingerprint of the full ordered port catalogue bound to this runtime body
/// (a fragment key input; changing any port contract invalidates fragments).
pub fn port_catalog_fingerprint() -> String {
    crate::ports::default_stdlib_port_catalog(RUNTIME_BODY).canonical_fingerprint()
}

/// Deterministic SHA-256 of the runtime body (binds port contracts and keys).
pub fn runtime_body_sha256() -> String {
    sha256_hex(RUNTIME_BODY.as_bytes())
}

/// Every helper/export the runtime exposes (used by the printer to emit the
/// exact named import list and by the declaration/body consistency check).
pub fn runtime_export_names() -> &'static [&'static str] {
    crate::runtime::EXPORT_NAMES
}

