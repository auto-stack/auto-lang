/// The §5.1 program, VERBATIM except two surface spellings the aggregates
/// grammar freezes differently (identical semantics; recorded in the plan):
/// `lr: 0.1d` (961 float suffix) and `for step < 60` (the aggregates
/// conditional-loop spelling). Kept in lockstep with the corpus copy.
const ACCEPTANCE: &str = r#"use.py torch: manual_seed, arange, ones
use.py torch.nn: Linear, MSELoss
use.py torch.optim: SGD

fn main() int {
    manual_seed(0)
    var x = arange(8).reshape(4, 2) / 2
    var target = ones(4, 1)
    var model = Linear(2, 1, bias: false)
    var loss_fn = MSELoss()
    var mparams = model.parameters()
    var lr_v = 0.1d
    var optimizer = SGD(mparams, lr: lr_v)
    var step = 0
    for step < 60 {
        var prediction = model(x)
        var loss = loss_fn(prediction, target)
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()
        print(loss.to(float))
        step = step + 1
    }
    var prediction = model(x)
    print(prediction.shape)
    print(prediction[0].to(float))
    return 0
}"#;

/// The frozen independent reference (torch 2.14.0+cpu, seed 0; recorded
/// 2026-11-17 in plan-artifacts/plan-1026/ref/train_ref_out.json — NOT
/// generated by ACE, no adapter).
const REF_FIRST_LOSS: f32 = 0.2370201051235199;
const REF_FINAL_LOSS: f32 = 0.1013089045882225;
const REF_PRED0: f32 = 0.4728480279445648;
const REF_SHAPE: &str = "torch.Size([4, 1])";

#[test]
fn p1026_corpus_identity_both_directions() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(CORPUS_COPY);
    let bytes = std::fs::read(&path)
        .unwrap_or_else(|e| panic!("corpus copy missing at {}: {e}", path.display()));
    let text = String::from_utf8(bytes).expect("corpus copy is UTF-8");
    assert_eq!(
        text, ACCEPTANCE,
        "the corpus copy must stay byte-identical to the frozen §5.1 program"
    );
}

#[test]
fn p1026_v01_acceptance_training_via_public_session() {
    let started = std::time::Instant::now();
    let mut session = PySession::open().expect("the py adapter session opens");
    // generous step/wall budgets: the f64 reconstruction's pow2 loop is
    // instruction-heavy by design (~1000 steps per extraction)
    let limits = ExecLimits {
        max_steps: 200_000_000,
        wall: std::time::Duration::from_secs(120),
        ..Default::default()
    };
    let run = session
        .run_with(&ACCEPTANCE, &limits)
        .unwrap_or_else(|e| panic!("lane: {e}"));
    let elapsed = started.elapsed();
    eprintln!(
        "V01 outcome {:?} in {} ms (steps hidden in outcome)",
        run.outcome,
        elapsed.as_millis()
    );
    assert!(
        run.success_i32().is_some(),
        "the run must succeed: {:?}",
        run.outcome
    );
    let text = run.stdout_text();
    let lines: Vec<&str> = text.lines().collect();
    assert_eq!(lines.len(), 62, "60 losses + shape + pred0");
    // 60 finite losses, monotonically converging (final < first, < 1)
    let first: f32 = lines[0].parse().expect("first loss parses as f32");
    let last: f32 = lines[59].parse().expect("last loss parses as f32");
    assert_eq!(
        lines[0], "0.2370201",
        "the first-loss line is pinned string-exactly (the corrupted          reconstructions 0.23701999/0.2370199859 must never return)"
    );
    assert!((first - REF_FIRST_LOSS).abs() < 1e-6, "first loss {first}");
    assert!((last - REF_FINAL_LOSS).abs() < 1e-6, "final loss {last}");
    assert!(last < first && last < 1.0, "training converges");
    // the shape display and the final prediction read back through the
    // staged-text channel and the f64 bits pair
    assert_eq!(lines[60], REF_SHAPE, "shape display");
    let pred0: f32 = lines[61].parse().expect("pred0 parses as f32");
    assert!((pred0 - REF_PRED0).abs() < 1e-5, "pred0 {pred0}");
    // 2026-11-14 discipline: per-case measured duration
    eprintln!("V01 case duration: {} ms", elapsed.as_millis());
}

#[test]
fn p1026_session_close_releases_binding_and_reopens() {
    let mut session = PySession::open().expect("session opens");
    session.close();
    // a fresh session at a new generation still runs a py op end-to-end
    let mut fresh = PySession::open().expect("fresh session opens");
    let run = fresh
        .run("use.py math: sqrt\nfn main() int {\nvar q = sqrt(4)\nprint(q.to(float))\nreturn 0\n}")
        .unwrap_or_else(|e| panic!("fresh run: {e}"));
    assert!(run.success_i32().is_some(), "{:?}", run.outcome);
    assert_eq!(run.stdout_text().lines().count(), 1, "one print line");
    let v: f32 = run
        .stdout_text()
        .lines()
        .next()
        .unwrap()
        .parse()
        .expect("sqrt(4) display parses");
    assert!((v - 2.0).abs() < 1e-6, "sqrt(4)=2.0 via the public session");
}

/// F-1 durable witnesses (REVIEW ROUND 2, F-11): the f64 bits-pair
/// reconstruction is pinned through GENUINE Python crossings — the values
/// come FROM Python (`use.py math: pi, e`, py_binop/py member objects), so
/// `.to(float)`/`.to(double)` route through py_to_f64 → __py_f64_bits.
/// e = 2.718281828459045 has lo32 = 0x8B145769 (bit 31 SET); pi - 6 is a
/// NEGATIVE value (sign bit + negative hi word). Both asserted EXACTLY
/// (== against Rust-computed constants — no tolerance).
#[test]
fn p1026_f64_reconstruction_bit_exact_negative_and_low_bit31() {
    let mut session = PySession::open().expect("session opens");
    let run = session
        .run(
            "use.py math: pi, e
fn main() int {
var d = pi - 6
var g = e
print(d.to(float))
print(g.to(float))
print(d.to(double))
return 0
}",
        )
        .unwrap_or_else(|e| panic!("crossing run: {e}"));
    assert!(run.success_i32().is_some(), "{:?}", run.outcome);
    let text = run.stdout_text();
    let lines: Vec<&str> = text.lines().collect();
    assert_eq!(lines.len(), 3, "three prints: {text:?}");
    // negative crossing (pi - 6 < 0): the f32 print must be EXACTLY the
    // f32 rounding of the true f64 — == not tolerance
    let neg: f32 = lines[0].parse().expect("negative display parses");
    let expect_neg = (std::f64::consts::PI - 6.0) as f32;
    assert_eq!(
        neg.to_bits(),
        expect_neg.to_bits(),
        "pi-6 must reconstruct bit-exactly through py_to_f64/__py_f64_bits"
    );
    // positive lo-bit31 crossing (e: lo32 = 0x8B145769, bit 31 set)
    let epos: f32 = lines[1].parse().expect("e display parses");
    assert_eq!(
        epos.to_bits(),
        (std::f64::consts::E as f32).to_bits(),
        "e (lo-bit31 class) must reconstruct bit-exactly"
    );
    // the f64 lane on the negative value — full double exactness
    let neg64: f64 = lines[2].parse().expect("negative double display parses");
    assert_eq!(
        neg64.to_bits(),
        (std::f64::consts::PI - 6.0).to_bits(),
        "pi-6 as double must be bit-exact"
    );
}

/// F-4 / V-09: Python object IDENTITY — in-place mutation through one AV
/// reference is visible through an alias; the bridge holds ONE object
/// (never a copy). V-10: dynamic state — getitem succeeds only after the
/// mutation that created the element (the object's observable shape
/// changed between calls).
#[test]
fn p1026_v09_v10_identity_mutation_and_dynamic_state() {
    let mut session = PySession::open().expect("session opens");
    // build a Python list, mutate via `l.append`, read via ALIAS `a` and
    // via getitem — identity + dynamic state in one program
    let run = session
        .run(
            "use.py builtins: list
fn main() int {
var l = list()
var a = l
l.append(41)
var v = a[0]
l.append(1)
var w = a[1]
var s = v + w
return s.to(int)
}",
        )
        .unwrap_or_else(|e| panic!("identity run: {e}"));
    assert_eq!(
        run.success_i32(),
        Some(42),
        "alias a sees both appends (identity; a[1] exists only AFTER the second append — dynamic state): {:?}",
        run.outcome
    );
    // the pre-mutation getitem is the named IndexError (dynamic-state
    // negative leg): reading a[0] on an EMPTY list must trap
    let run2 = session
        .run(
            "use.py builtins: list
fn main() int {
var l = list()
var v = l[0]
return 1
}",
        )
        .unwrap_or_else(|e| panic!("empty-getitem run: {e}"));
    match run2.outcome {
        ace_av_core::contract::ExecOutcome::Trap { .. } => {}
        other => panic!("empty-list getitem must trap (IndexError), got {other:?}"),
    }
}

/// F-2 witness: a SCALAR-ONLY infinite loop must hit the InstrSteps budget
/// (the accidentally-deleted per-iteration step charge froze this for all
/// profiles — restored with an explicit bound here).
#[test]
fn p1026_f02_scalar_infinite_loop_hits_step_budget() {
    // plain (non-foreign) pipeline: a pure-scalar spin with NO calls —
    // only the per-iteration step charge can bound it
    let src = "fn main() int {
var x = 0
for x < 1 { x = x * 1 }
return x
}";
    let compiled = ace_core::source::compile_aggregates_source(src, "spin.at", &[]).unwrap();
    let mir = ace_lowering::lower_checked_closures(&compiled.checked, "d_main", 0).unwrap();
    let encoded = ace_av_core::abc::encode_abc(&mir).unwrap().to_flat();
    let decoded = ace_av_core::abc::decode_abc(&encoded).unwrap();
    let loaded = ace_av_core::abc_verify::verify_abc_bytes(&encoded, &mir.owner).unwrap();
    let out = ace_av_core::av::execute(
        &loaded,
        &ExecLimits {
            max_steps: 50_000,
            ..Default::default()
        },
        &ace_av_core::av::CancelFlag::new(false),
    )
    .0;
    match out {
        ace_av_core::contract::ExecOutcome::Resource {
            kind: ace_av_core::contract::ResourceKind::InstrSteps,
            ..
        } => {}
        other => panic!("scalar spin must hit InstrSteps, got {other:?}"),
    }
}
