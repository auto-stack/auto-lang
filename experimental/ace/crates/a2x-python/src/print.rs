//! PLAN-1042: deterministic whole-program Python printer and line source-map
//! generator shared across Scalar, RecordText, and Collections assembly.

use ace_a2x_core::{A2xReject, FragmentText};

use crate::lower::{py_fn_name, py_method_name};

/// Version tag of the Python source printer format.
pub const PY_PRINT_VERSION: &str = "a2x-py-print/1";

/// Deterministic source-map entry linking an Auto source declaration + origin span
/// to exact 1-based line numbers inside `generated.py`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SourceMapEntry {
    pub decl: String,
    pub decl_kind: String,
    pub origin_start: u32,
    pub origin_end: u32,
    pub gen_line_start: usize,
    pub gen_line_end: usize,
}

/// Output bundle of [`print_program_py`].
#[derive(Clone, Debug)]
pub struct PrintedPyProgram {
    pub generated_py: String,
    pub main_py: String,
    pub source_map: Vec<SourceMapEntry>,
    pub source_map_json: String,
}

fn parse_origin_header(line: &str) -> Option<(u32, u32)> {
    let rest = line.strip_prefix("# origin: ")?;
    let span_part = rest.split_whitespace().next()?;
    let (s, e) = span_part.split_once("..")?;
    Some((s.parse().ok()?, e.parse().ok()?))
}

fn entry_py_symbol(entry: &str, fragments: &[FragmentText<'_>]) -> Result<String, A2xReject> {
    let frag = fragments
        .iter()
        .find(|f| f.source_name == entry)
        .ok_or_else(|| A2xReject::entry("entry missing"))?;
    for line in frag.text.lines() {
        if let Some(rest) = line.strip_prefix("def ") {
            if let Some(sig) = rest.split('(').next() {
                if !rest.contains("():") && !rest.ends_with("():") {
                    return Err(A2xReject::entry(
                        "entry function must take zero parameters for a2x_main.py",
                    ));
                }
                return Ok(sig.trim().to_string());
            }
        }
    }
    Ok(py_fn_name(entry))
}

fn json_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out
}

/// Print `generated.py`, `a2x_main.py`, and `source_map.json` deterministically from
/// cached or freshly lowered function fragments plus optional prelude helper text.
pub fn print_program_py(
    prelude_helpers: &str,
    fragments: &[FragmentText<'_>],
    entry: &str,
    origins: Option<&[(usize, (u32, u32))]>,
    schema: &str,
    input_hash: &str,
) -> Result<PrintedPyProgram, A2xReject> {
    let entry_symbol = entry_py_symbol(entry, fragments)?;

    let mut generated = String::new();
    generated.push_str(&format!(
        "# AUTO-GENERATED BY {PY_PRINT_VERSION} ({schema}) — DO NOT EDIT.\n\
         # input_hash: {input_hash}\n\
         from a2x_py_runtime import *\n\n"
    ));

    if !prelude_helpers.is_empty() {
        generated.push_str(prelude_helpers);
        if !prelude_helpers.ends_with('\n') {
            generated.push('\n');
        }
    }

    let mut cur_line = generated.lines().count() + 1;
    let mut source_map = Vec::with_capacity(fragments.len());

    for frag in fragments {
        let trimmed = frag.text.trim_end_matches('\n');
        let line_count = trimmed.lines().count().max(1);
        let parsed_origin = frag.text.lines().next().and_then(parse_origin_header);
        let fallback_origin = origins
            .and_then(|o| o.iter().find(|(d, _)| *d == frag.def_index))
            .map(|o| o.1)
            .unwrap_or((0, 0));
        let (origin_start, origin_end) = parsed_origin.unwrap_or(fallback_origin);

        let decl_kind = if frag
            .text
            .lines()
            .any(|l| l.starts_with(&format!("def {}", py_method_name(&frag.source_name))))
        {
            "method"
        } else {
            "fn"
        };

        let gen_line_start = cur_line;
        let gen_line_end = cur_line + line_count - 1;
        source_map.push(SourceMapEntry {
            decl: frag.source_name.to_string(),
            decl_kind: decl_kind.to_string(),
            origin_start,
            origin_end,
            gen_line_start,
            gen_line_end,
        });

        generated.push_str(trimmed);
        generated.push_str("\n\n");
        cur_line = gen_line_end + 2;
    }

    let main_py = format!(
        "# AUTO-GENERATED BY {PY_PRINT_VERSION} ({schema}) — DO NOT EDIT.\n\
         import sys\n\
         from a2x_py_runtime import a2x_run_main\n\
         import generated\n\n\
         if __name__ == '__main__':\n\
             sys.exit(a2x_run_main(generated.{entry_symbol}))\n"
    );

    let mut sm = String::from("{\n  \"version\": \"");
    sm.push_str(PY_PRINT_VERSION);
    sm.push_str("\",\n  \"entry\": \"");
    sm.push_str(&json_escape(entry));
    sm.push_str("\",\n  \"entries\": [\n");
    for (idx, item) in source_map.iter().enumerate() {
        let comma = if idx + 1 < source_map.len() { "," } else { "" };
        sm.push_str(&format!(
            "    {{ \"decl\": \"{}\", \"decl_kind\": \"{}\", \"origin\": [{}, {}], \"generated_lines\": [{}, {}] }}{}\n",
            json_escape(&item.decl),
            json_escape(&item.decl_kind),
            item.origin_start,
            item.origin_end,
            item.gen_line_start,
            item.gen_line_end,
            comma
        ));
    }
    sm.push_str("  ]\n}\n");

    Ok(PrintedPyProgram {
        generated_py: generated,
        main_py,
        source_map,
        source_map_json: sm,
    })
}
