//! Versioned Python 3 runtime helper generator (`a2x_py_runtime.py`).
//!
//! All Auto semantics that Python would otherwise alter (checked 32-bit signed
//! arithmetic, C/Rust truncation-toward-zero `/` and `%`, byte-exact UTF-8 and
//! embedded NUL `str`/`Str`, Unicode scalar `char`, explicit verifier-scheduled
//! release without Python GC reliance, and explicit closeable resource handles +
//! standard-operation port dispatch) live in this single self-contained module.

use ace_core::runtime_contract::sha256_hex;

pub const PY_RUNTIME_VERSION: &str = "a2x-py-runtime/1";

/// Deterministic SHA-256 of the core Python runtime body used to bind port contracts.
pub fn runtime_body_sha256() -> String {
    sha256_hex(RUNTIME_BODY.as_bytes())
}

pub fn python_runtime_source(marks: &[&'static str]) -> String {
    let mut out = String::with_capacity(RUNTIME_BODY.len() + 512);
    out.push_str("# AUTO-GENERATED by auto-a2x-python (PLAN-1042) -- DO NOT EDIT.\n");
    out.push_str(&format!(
        "A2X_PY_RUNTIME_VERSION = {:?}\n",
        PY_RUNTIME_VERSION
    ));
    let body_hash = sha256_hex(RUNTIME_BODY.as_bytes());
    out.push_str(&format!("A2X_PY_RUNTIME_BODY_SHA256 = {:?}\n", body_hash));
    out.push_str(RUNTIME_BODY);
    for &mark in marks {
        let (suffix, val) = if mark == "hir.test.mark_a" {
            ("a", 1i32)
        } else {
            ("b", 2i32)
        };
        out.push_str(&format!(
            "\ndef a2x_mark_{suf}() -> int:\n\
             \x20   _RT.marks.append(\"mark_{suf}\")\n\
             \x20   sys.stderr.buffer.write(b\"mark_{suf}\\n\")\n\
             \x20   return {val}\n",
            suf = suffix,
            val = val
        ));
    }
    out
}

