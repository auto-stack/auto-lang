//! PLAN-933 T-04: the independent oracle for the twenty tracked
//! `a2r-hir-collections-904` golden `manifest.json` files (D-931-3
//! landed them via the daily-emit channel; this module proves they are
//! byte-for-byte derivable from TRACKED materials + the frozen contract
//! alone — no emitter call, no actual backfill).
//!
//! Independence contract (plan §5.2/§5.4):
//! * this module imports NO `ace-*` crate — it does not call the
//!   production emitter `build_coll_manifest`/`assemble_...` or any
//!   workspace hash helper. FNV-1a-64 and SHA-256 are implemented here
//!   from the public algorithms and self-checked against published test
//!   vectors (FIPS 180-4 / draft-eastlake-fnv);
//! * every manifest field's source is frozen and tracked:
//!   - schema `auto.a2x.rust.collections.fileset/1` — spec
//!     docs/specs/auto-test-case/a2r-hir-certification.md (4-file
//!     fileset contract, manifest binds full-source sha + config);
//!   - `source_profile` `auto.source.collections.draft` /
//!     `hir_domain` `collections-draft` — spec
//!     docs/specs/auto-a2r/collections-hir-backend.md, cross-pinned by
//!     every frozen generated.rs header;
//!   - `input_hash` = FNV-1a-64 over the tracked `src/<case>.at` bytes
//!     (public algorithm; the format "input hash (fnv1a-64)" is frozen
//!     in every generated.rs header);
//!   - `source_sha256` = SHA-256 over the SAME tracked source bytes
//!     ("binds the REPLACED FULL SOURCE sha256" — never a fragment);
//!   - `execution_config` = the frozen canonical debug default
//!     (PLAN-904 §5.6 fixed key order; the case sends no overrides),
//!     byte-pinned by every generated.rs header;
//!   - `entry`/`entry_fn` = the case's frozen entry `main` and the
//!     frozen `fn_main` call inside golden main.rs / generated.rs header;
//!   - `target` = the frozen v1 profile pinned by the golden file
//!     headers ("AUTO-GENERATED by auto-a2x-rust v0.1.0", rustc
//!     `--edition 2021` certification legs) + `a2x-coll/1`;
//!   - `files` = the three tracked golden files, order frozen by the
//!     fileset contract, hashes recomputed here from their bytes;
//! * byte template: 2-space top-level keys `"k": v`, inline compact
//!   objects for execution_config/target/files entries, single trailing
//!   LF — the reviewed-golden byte format itself.
//!
//! The V-07 legs prove this oracle DISTINGUISHES wrong values: wrong
//! hash algorithm input, wrong key order, dropped LF, near-neighbor
//! schema/config literals, and tampered golden copies are all rejected
//! (byte + typed parse axes).

