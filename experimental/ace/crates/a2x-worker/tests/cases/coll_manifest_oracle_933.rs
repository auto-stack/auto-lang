/// Reconstruct the manifest TEXT from tracked inputs + frozen contract
/// (the independent reference; `input_hash_hex`, `source_sha_hex` and
/// `file_hashes` are supplied so negative legs can feed wrong values).
#[allow(clippy::too_many_arguments)]
fn reconstruct(
    input_hash_hex: &str,
    source_sha_hex: &str,
    config_line: &str,
    schema: &str,
    target_line: &str,
    files: &[(&str, &str)],
    trailing_lf: bool,
) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str(&format!("  \"schema\": \"{schema}\",\n"));
    out.push_str(&format!("  \"source_profile\": \"{SOURCE_PROFILE}\",\n"));
    out.push_str(&format!("  \"hir_domain\": \"{HIR_DOMAIN}\",\n"));
    out.push_str(&format!("  \"input_hash\": \"{input_hash_hex}\",\n"));
    out.push_str(&format!("  \"source_sha256\": \"{source_sha_hex}\",\n"));
    out.push_str(&format!("  \"execution_config\": {config_line},\n"));
    out.push_str(&format!("  \"entry\": \"{ENTRY}\",\n"));
    out.push_str(&format!("  \"entry_fn\": \"{ENTRY_FN}\",\n"));
    out.push_str(&format!("{target_line}\n"));
    out.push_str("  \"files\": [\n");
    for (i, (path, hash)) in files.iter().enumerate() {
        let comma = if i + 1 < files.len() { "," } else { "" };
        out.push_str(&format!(
            "    {{ \"path\": \"{path}\", \"sha256\": \"{hash}\" }}{comma}\n"
        ));
    }
    out.push_str("  ]\n}");
    if trailing_lf {
        out.push('\n');
    }
    out
}

/// The positive reconstruction for one case: independently computed
/// hashes + frozen literals, byte-compared against the tracked golden.
fn reconstruct_case(case: &str, root: &Path) -> String {
    let src = std::fs::read(root.join("src").join(format!("{case}.at")))
        .unwrap_or_else(|e| panic!("{case}: read source: {e}"));
    let input_hash = format!("{:016x}", fnv1a64(&src));
    let source_sha = hex_lower(&sha256(&src));
    let files: Vec<(String, String)> = GOLDEN_FILES
        .iter()
        .map(|f| {
            let bytes =
                std::fs::read(root.join(format!("golden-{case}")).join(f)).expect("golden file");
            (f.to_string(), hex_lower(&sha256(&bytes)))
        })
        .collect();
    let files_ref: Vec<(&str, &str)> = files
        .iter()
        .map(|(p, h)| (p.as_str(), h.as_str()))
        .collect();
    reconstruct(
        &input_hash,
        &source_sha,
        EXECUTION_CONFIG,
        SCHEMA,
        TARGET_LINE,
        &files_ref,
        true,
    )
}

/// V-03/V-07: every one of the twenty tracked manifests is byte-for-byte
/// the independent reconstruction from tracked inputs + frozen contract,
/// the frozen generated.rs headers agree with the independently computed
/// identity fields, and the suite/case inventory is conserved.
#[test]
fn coll_oracle_933_twenty_manifests_independently_reconstructed() {
    let root = case_root();
    // inventory conservation: exactly the twenty golden dirs / sources,
    // each golden dir exactly the four contracted files
    let mut golden_dirs: BTreeSet<String> = BTreeSet::new();
    for entry in std::fs::read_dir(&root).unwrap().flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        if name.starts_with("golden-") {
            golden_dirs.insert(name);
        }
    }
    let expect_dirs: BTreeSet<String> = CASES.iter().map(|c| format!("golden-{c}")).collect();
    assert_eq!(golden_dirs, expect_dirs, "golden dirs are exactly the 20");
    let mut src_files: BTreeSet<String> = BTreeSet::new();
    for entry in std::fs::read_dir(root.join("src")).unwrap().flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        if name.ends_with(".at") {
            src_files.insert(name);
        }
    }
    let expect_src: BTreeSet<String> = CASES.iter().map(|c| format!("{c}.at")).collect();
    assert_eq!(src_files, expect_src, "src/ is exactly the 20 sources");

    for case in CASES {
        let gdir = root.join(format!("golden-{case}"));
        let names: BTreeSet<String> = std::fs::read_dir(&gdir)
            .unwrap()
            .flatten()
            .map(|e| e.file_name().to_string_lossy().to_string())
            .collect();
        let mut want: BTreeSet<String> = GOLDEN_FILES.iter().map(|f| f.to_string()).collect();
        want.insert("manifest.json".to_string());
        assert_eq!(names, want, "{case}: golden dir is exactly the 4 files");

        let golden_manifest = std::fs::read_to_string(gdir.join("manifest.json"))
            .unwrap_or_else(|e| panic!("{case}: read golden manifest: {e}"));
        let rebuilt = reconstruct_case(case, &root);
        assert_eq!(
            rebuilt, golden_manifest,
            "{case}: golden manifest must equal the independent reconstruction"
        );

        // typed cross-axis: both parse to the SAME JSON structure
        let a: serde_json::Value = serde_json::from_str(&rebuilt).unwrap();
        let b: serde_json::Value = serde_json::from_str(&golden_manifest).unwrap();
        assert_eq!(a, b, "{case}: typed manifest equality");

        // frozen-header agreement: generated.rs pins the identity fields
        let generated = std::fs::read_to_string(gdir.join("generated.rs")).unwrap();
        let src = std::fs::read(root.join("src").join(format!("{case}.at"))).unwrap();
        let input_hash = format!("{:016x}", fnv1a64(&src));
        let source_sha = hex_lower(&sha256(&src));
        assert!(
            generated.contains(&format!(
                "// source profile: {SOURCE_PROFILE} | hir domain: {HIR_DOMAIN} | input hash (fnv1a-64): {input_hash}"
            )),
            "{case}: generated.rs header pins profile/domain/input-hash"
        );
        assert!(
            generated.contains(&format!(
                "// source sha256 (full replaced source): {source_sha}"
            )),
            "{case}: generated.rs header pins the full-source sha"
        );
        assert!(
            generated.contains(&format!("// execution config: {EXECUTION_CONFIG}")),
            "{case}: generated.rs header pins the execution config"
        );
        assert!(
            generated.contains(&format!("// entry: `{ENTRY}` -> `{ENTRY_FN}`")),
            "{case}: generated.rs header pins the entry mapping"
        );
        assert!(
            generated.contains("AUTO-GENERATED by auto-a2x-rust v0.1.0"),
            "{case}: generated.rs header pins backend/version"
        );
        // golden main.rs calls the frozen entry fn
        let main_rs = std::fs::read_to_string(gdir.join("main.rs")).unwrap();
        assert!(
            main_rs.contains(&format!("generated::{ENTRY_FN}()")),
            "{case}: golden main.rs calls {ENTRY_FN}"
        );
        // the golden manifest's own file hashes must match the tracked
        // golden bytes (manifest pins its siblings)
        for f in GOLDEN_FILES {
            let bytes = std::fs::read(gdir.join(f)).unwrap();
            let h = hex_lower(&sha256(&bytes));
            assert!(
                golden_manifest.contains(&h),
                "{case}: manifest pins the real sha256 of {f}"
            );
        }
    }
}

/// V-07: the oracle DISTINGUISHES wrong derivations — each mutated
/// reconstruction must NOT equal the tracked golden (a self-consistent
/// but wrong reference could otherwise masquerade as the oracle).
#[test]
fn coll_oracle_933_rejects_wrong_derivations() {
    let root = case_root();
    let case = "L04";
    let golden =
        std::fs::read_to_string(root.join(format!("golden-{case}/manifest.json"))).unwrap();
    let src = std::fs::read(root.join("src").join(format!("{case}.at"))).unwrap();
    let input_hash = format!("{:016x}", fnv1a64(&src));
    let source_sha = hex_lower(&sha256(&src));
    let files: Vec<(String, String)> = GOLDEN_FILES
        .iter()
        .map(|f| {
            let bytes = std::fs::read(root.join(format!("golden-{case}")).join(f)).unwrap();
            (f.to_string(), hex_lower(&sha256(&bytes)))
        })
        .collect();
    let files_ref: Vec<(&str, &str)> = files
        .iter()
        .map(|(p, h)| (p.as_str(), h.as_str()))
        .collect();

    let right =
        |ih: &str, sha: &str, cfg: &str, schema: &str, tgt: &str, fs: &[(&str, &str)], lf: bool| {
            reconstruct(ih, sha, cfg, schema, tgt, fs, lf)
        };

    // wrong input-hash: hash of the source MINUS one byte (off-input)
    let mut wrong_src = src.clone();
    wrong_src.pop();
    let wrong_ih = format!("{:016x}", fnv1a64(&wrong_src));
    assert_ne!(
        input_hash, wrong_ih,
        "mutation really changes the input hash"
    );
    assert_ne!(
        right(
            &wrong_ih,
            &source_sha,
            EXECUTION_CONFIG,
            SCHEMA,
            TARGET_LINE,
            &files_ref,
            true
        ),
        golden
    );

    // wrong source sha: hash of a different (neighbor case) source
    let neighbor = std::fs::read(root.join("src/L05.at")).unwrap();
    let wrong_sha = hex_lower(&sha256(&neighbor));
    assert_ne!(source_sha, wrong_sha);
    assert_ne!(
        right(
            &input_hash,
            &wrong_sha,
            EXECUTION_CONFIG,
            SCHEMA,
            TARGET_LINE,
            &files_ref,
            true
        ),
        golden
    );

    // near-neighbor config literal (2^24-1)
    assert_ne!(
        right(
            &input_hash,
            &source_sha,
            "{\"budget_work_units\":16777215,\"cancel\":false,\"events\":false,\"fault_alloc\":null,\"mode\":\"debug\"}",
            SCHEMA,
            TARGET_LINE,
            &files_ref,
            true
        ),
        golden
    );

    // near-neighbor schema (fileset/2)
    assert_ne!(
        right(
            &input_hash,
            &source_sha,
            EXECUTION_CONFIG,
            "auto.a2x.rust.collections.fileset/2",
            TARGET_LINE,
            &files_ref,
            true
        ),
        golden
    );

    // wrong files ORDER (runtime before main)
    let swapped: Vec<(&str, &str)> = vec![files_ref[1], files_ref[0], files_ref[2]];
    assert_ne!(
        right(
            &input_hash,
            &source_sha,
            EXECUTION_CONFIG,
            SCHEMA,
            TARGET_LINE,
            &swapped,
            true
        ),
        golden
    );

    // dropped trailing LF
    assert_ne!(
        right(
            &input_hash,
            &source_sha,
            EXECUTION_CONFIG,
            SCHEMA,
            TARGET_LINE,
            &files_ref,
            false
        ),
        golden
    );

    // tampered GOLDEN copy: flip one hex char of source_sha256 — the
    // reconstruction (and the typed parse) must both disagree, i.e. a
    // tampered manifest is distinguishable from the real oracle
    let flipped = format!(
        "{}{}",
        &source_sha[..63],
        if source_sha.ends_with('0') { '1' } else { '0' }
    );
    let tampered = golden.replace(&source_sha, &flipped);
    assert_ne!(&tampered, &golden, "tamper really changed the golden copy");
    assert_ne!(reconstruct_case(case, &root), tampered);
    let t: serde_json::Value = serde_json::from_str(&tampered).unwrap();
    let r: serde_json::Value = serde_json::from_str(&reconstruct_case(case, &root)).unwrap();
    assert_ne!(t, r, "typed axis also rejects the tampered manifest");

    // missing files entry: a 2-file manifest is structurally different
    let two_files = &files_ref[..2];
    let two = right(
        &input_hash,
        &source_sha,
        EXECUTION_CONFIG,
        SCHEMA,
        TARGET_LINE,
        two_files,
        true,
    );
    let tv: serde_json::Value = serde_json::from_str(&two).unwrap();
    let rv: serde_json::Value = serde_json::from_str(&reconstruct_case(case, &root)).unwrap();
    assert_ne!(tv["files"].as_array().map(|a| a.len()), Some(3));
    assert_ne!(tv, rv);
}
