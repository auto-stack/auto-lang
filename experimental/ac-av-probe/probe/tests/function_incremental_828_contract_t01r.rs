use auto_ac_prototype::source as ac;

const ORIGINAL: &str = "fn helper(n int) int { return n + 1 }\nfn main() int { var x = helper(2); return x }\nfn tail() int { return 9 }\n";
const EDITED: &str = "fn helper(n int) int { return n + 2 }\nfn main() int { var x = helper(2); return x }\nfn tail() int { return 9 }\n";

fn item(src: &str, name: &str) -> ac::ast::FnItem {
    ac::parse_program_with(src, ac::SourceProfile::Scalar)
        .unwrap()
        .items
        .into_iter()
        .find_map(|x| {
            if let ac::ast::Item::Fn(f) = x {
                if f.name.name == name {
                    return Some(f);
                }
            }
            None
        })
        .unwrap()
}
fn dump(parts: &ac::SourceParts, def: &str) -> Vec<u8> {
    let m = &parts.bundle.modules[0];
    let body = m
        .defs
        .iter()
        .find_map(|d| {
            if d.id_text == def {
                if let auto_ac_prototype::hir::DefKind::Function { body, .. } = d.kind {
                    return Some(body);
                }
            }
            None
        })
        .unwrap();
    auto_av_probe::cache::canonical_hir_function(m, body)
}

#[test]
fn t01_review_valid_changed_body_matches_cold_control() {
    let parsed = ac::parse_program_with(ORIGINAL, ac::SourceProfile::Scalar).unwrap();
    let mut env = ac::resolve_env(&parsed, &[], ac::SourceProfile::Scalar).unwrap();
    // Actually run the full cold frontend before recording its baseline.
    ac::compile_parts_with(ORIGINAL, "probe.at", &[], ac::SourceProfile::Scalar).unwrap();
    ac::env_note_cold_walks(&mut env);
    ac::recheck_function(&mut env, &item(EDITED, "helper"), 0).unwrap();
    let (parts, _) = ac::emit_function_body(&env, 0, EDITED, "probe.at").unwrap();
    let cold = ac::compile_parts_with(EDITED, "probe.at", &[], ac::SourceProfile::Scalar).unwrap();
    assert_eq!(dump(&parts, "d_helper"), dump(&cold, "d_helper"));
    let def = parts.bundle.modules[0]
        .defs
        .iter()
        .position(|d| d.id_text == "d_helper")
        .unwrap();
    auto_ac_prototype::verify::verify_function(parts.bundle.clone(), def).unwrap();
    assert_eq!(ac::resolve::env_walk_stats(&env), (4, 4));
}

#[test]
fn t01_review_one_emission_must_not_regenerate_unchanged_body_documents() {
    let parsed = ac::parse_program_with(ORIGINAL, ac::SourceProfile::Scalar).unwrap();
    let mut env = ac::resolve_env(&parsed, &[], ac::SourceProfile::Scalar).unwrap();
    ac::recheck_function(&mut env, &item(EDITED, "helper"), 0).unwrap();
    let (parts, receipt) = ac::emit_function_body(&env, 0, EDITED, "probe.at").unwrap();
    let headers: Vec<&str> = parts
        .atom_text
        .lines()
        .map(str::trim_start)
        .filter(|l| l.starts_with("body "))
        .collect();
    eprintln!("receipt={receipt:?}; planned_fns={}; emitted_body_headers={headers:?}; freshly_bound_bodies={}",
        parts.planned_fns, parts.bundle.modules[0].bodies.len());
    // This measures bodies generated by THIS emission, not the cardinality
    // of a future shared declaration/context view.
    assert_eq!(
        headers.len(),
        1,
        "the hot single-body emitter must not regenerate main/tail bodies"
    );
}

#[test]
fn t01_review_real_old_pipeline_must_invalidate_same_structural_gate() {
    const BEFORE: &str =
        "fn helper(n int) int { return n + 1 }\nfn main() int { return helper(2) }\n";
    const AFTER: &str =
        "fn helper(n int) int { return n + 2 }\nfn main() int { return helper(2) }\n";
    let parsed = ac::parse_program_with(BEFORE, ac::SourceProfile::Scalar).unwrap();
    let mut env = ac::resolve_env(&parsed, &[], ac::SourceProfile::Scalar).unwrap();
    ac::compile_parts_with(BEFORE, "probe.at", &[], ac::SourceProfile::Scalar).unwrap();
    ac::env_note_cold_walks(&mut env);
    ac::recheck_function(&mut env, &item(AFTER, "helper"), 0).unwrap();
    // The window gate (T01-C02 fix): observation hangs on the REAL
    // resolve/typecheck/plan/bind producers, per function name — within
    // the seam's window only `helper` accumulates body work; any other
    // function's body work in the SAME window makes the gate red.
    use auto_ac_prototype::body_work::{capture_body_work, BodyWork};
    let gate = |window: &std::collections::BTreeMap<String, BodyWork>, changed: &str| {
        window.get(changed).map_or(false, |w| {
            w.resolve == 1 && w.typecheck == 1 && w.plan == 1 && w.bind == 1
        }) && window
            .iter()
            .all(|(n, w)| n == changed || *w == BodyWork::default())
    };
    let ((_, receipt), win) = capture_body_work(|| {
        ac::recheck_function(&mut env, &item(AFTER, "helper"), 0).unwrap();
        ac::emit_function_body(&env, 0, AFTER, "probe.at").unwrap()
    });
    assert_eq!(receipt.real_body_plans, 1);
    assert!(
        gate(&win, "helper"),
        "seam window: only helper worked: {win:?}"
    );

    // Execute the ACTUAL old synth pipeline inside its own observation
    // window — its unchanged-function body work is producer-recorded and
    // the SAME gate must go red on it.
    let mut synth = ac::parse_program_with(AFTER, ac::SourceProfile::Scalar).unwrap();
    for x in &mut synth.items {
        if let ac::ast::Item::Fn(f) = x {
            if f.name.name != "helper" {
                f.body.stmts.clear();
            }
        }
    }
    let (old, old_win) = capture_body_work(|| {
        ac::compile_program_parts(&synth, AFTER, "probe.at", &[], ac::SourceProfile::Scalar)
            .unwrap()
    });
    assert_eq!(old.planned_fns, 2, "actual full synth producer executed");
    eprintln!("old_pipeline_window={old_win:?}");
    assert!(
        !gate(&old_win, "helper"),
        "actual extra whole-program body work is producer-observed and red: {old_win:?}"
    );
}

#[test]
fn t01_review_nonfirst_recursive_function_is_accepted_control() {
    let before = "fn main() int { return helper(2) }\nfn helper(n int) int { if n > 0 { return helper(n - 1) + 1 } else { return 0 } }\n";
    let after = before.replacen("+ 1", "+ 2", 1);
    let parsed = ac::parse_program_with(before, ac::SourceProfile::Scalar).unwrap();
    let mut env = ac::resolve_env(&parsed, &[], ac::SourceProfile::Scalar).unwrap();
    ac::recheck_function(&mut env, &item(&after, "helper"), 1).unwrap();
    let (parts, _) = ac::emit_function_body(&env, 1, &after, "probe.at").unwrap();
    let cold = ac::compile_parts_with(&after, "probe.at", &[], ac::SourceProfile::Scalar).unwrap();
    assert_eq!(dump(&parts, "d_helper"), dump(&cold, "d_helper"));
    let def = parts.bundle.modules[0]
        .defs
        .iter()
        .position(|d| d.id_text == "d_helper")
        .unwrap();
    auto_ac_prototype::verify::verify_function(parts.bundle.clone(), def).unwrap();
}
