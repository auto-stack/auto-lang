# PLAN-825 LoadedProgram scoped acceptance driver. Unimplemented scopes fail
# explicitly; a zero-selected, ignored, or missing mandatory case is never PASS.
[CmdletBinding()]
param(
    [Parameter(ParameterSetName = 'Scope', Mandatory = $true)]
    [ValidateSet("first", "targeted", "compat", "incremental", "bench", "baseline", "acceptance")]
    [string]$Scope,
    [Parameter(ParameterSetName = 'Guard')]
    [switch]$GuardSelfTest
)

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot | Split-Path -Parent
$probe = Join-Path $root 'experimental/ac-av-probe'

function Assert-Selected {
    param([string]$Output, [string]$Label, [string[]]$RequiredIds)
    if ($Output -notmatch 'test result:') { throw "$Label : no test-result line" }
    if ($Output -match 'test result: ok\. 0 passed; 0 failed') {
        throw "$Label : zero tests selected"
    }
    if ($Output -match ';\s*(\d+) ignored') {
        if ([int]$Matches[1] -gt 0) { throw "$Label : ignored/skipped mandatory case" }
    }
    foreach ($id in $RequiredIds) {
        $count = ([regex]::Matches($Output, "(?m)^test $([regex]::Escape($id)) .* (?:ok|FAILED|ignored).*$")).Count
        if ($count -ne 1) { throw "$Label : required case '$id' occurred $count times" }
    }
}

function Invoke-Cargo {
    param([string[]]$CargoArgs)
    $previous = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $script:out = & cargo @CargoArgs 2>&1 | Out-String
        $script:exitCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previous
    }
    Write-Host $script:out
    if ($script:exitCode -ne 0) { throw "cargo $($CargoArgs -join ' ') failed with exit $script:exitCode" }
    return $script:out
}

function Invoke-Native {
    param([string]$Exe, [string[]]$NativeArgs, [string]$Log)
    $previous = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $out = & $Exe @NativeArgs 2>&1 | Tee-Object -FilePath $Log | Out-String
        $code = $LASTEXITCODE
    } finally { $ErrorActionPreference = $previous }
    Write-Host $out
    if ($code -ne 0) { throw "$Exe failed with exit $code" }
}

function Assert-TierEvidence {
    param([string]$JsLog, [string]$LiftoffLog, [string]$TurboLog)
    $js = Get-Content -LiteralPath $JsLog -Raw -Encoding UTF8
    $liftoff = Get-Content -LiteralPath $LiftoffLog -Raw -Encoding UTF8
    $turbo = Get-Content -LiteralPath $TurboLog -Raw -Encoding UTF8
    if ($js -notmatch '\[generated bytecode for function:') { throw 'V8 JS Ignition evidence missing' }
    if ([regex]::Matches($liftoff, 'using Liftoff').Count -lt 8) { throw 'Wasm Liftoff evidence missing for required workloads' }
    if ([regex]::Matches($turbo, 'using TurboFan').Count -lt 8) { throw 'Wasm optimizing-tier evidence missing for required workloads' }
}

function Assert-MissingPeakControl {
    $raw = Join-Path $root 'docs/plans/attachments/825/bench-r6'
    $guard = Join-Path $raw 'guard'
    if (Test-Path $guard) { Remove-Item -LiteralPath $guard -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $guard | Out-Null
    Get-ChildItem -LiteralPath $raw -Filter '*.jsonl' -File | Where-Object { $_.Name -in @('av.jsonl', 'js.jsonl', 'liftoff.jsonl', 'turbofan.jsonl') } | ForEach-Object { Copy-Item $_.FullName -Destination $guard }
    $peakFile = Join-Path $guard 'js.jsonl'
    $withoutPeak = @(Get-Content -LiteralPath $peakFile -Encoding UTF8 | Where-Object { $_ -notmatch 'process-peak' })
    Set-Content -LiteralPath $peakFile -Value $withoutPeak -Encoding UTF8
    $failed = $false
    try {
        & powershell -NoProfile -File (Join-Path $root 'scripts/av-825-bench-report.ps1') -RawDir $guard -OutFile (Join-Path $guard 'bad.json') 2>$null
        if ($LASTEXITCODE -ne 0) { $failed = $true }
    } catch { $failed = $true }
    if (-not $failed) { throw 'missing process-peak counter-control was accepted' }
    Remove-Item -LiteralPath $guard -Recurse -Force
    exit 0
}

function Get-Fnv64Hex {
    param([string]$Path)
    [uint64]$hash = 14695981039346656037
    foreach ($byte in [IO.File]::ReadAllBytes($Path)) {
        $hash = ($hash -bxor [uint64]$byte) * 1099511628211
    }
    $hash.ToString('x16')
}

function Assert-BenchmarkEvidence {
    $raw = Join-Path $root 'docs/plans/attachments/825/bench-r6'
    $summaryPath = Join-Path $raw 'summary.json'
    $turnaroundPath = Join-Path $raw 'turnaround-summary.json'
    $summary = Get-Content -LiteralPath $summaryPath -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($summary.total_rows -ne 1720 -or $summary.groups.Count -ne 40) { throw 'benchmark group/row completeness mismatch' }
    foreach ($file in $summary.raw_files) {
        if ((Get-FileHash $file.path -Algorithm SHA256).Hash.ToLower() -ne $file.sha256) { throw "benchmark raw identity changed: $($file.path)" }
    }
    $avFirst = Get-Content -LiteralPath (Join-Path $raw 'av.jsonl') -TotalCount 1 -Encoding UTF8 | ConvertFrom-Json
    $currentFp = Get-Fnv64Hex -Path (Join-Path $probe 'target/release/av_runtime_825_bench.exe')
    if ($avFirst.binary_fnv64 -ne $currentFp) { throw 'benchmark binary identity is stale' }
    Assert-TierEvidence -JsLog (Join-Path $raw 'js-tier.log') -LiftoffLog (Join-Path $raw 'liftoff-tier.log') -TurboLog (Join-Path $raw 'turbofan-tier.log')
    $turnaround = Get-Content -LiteralPath $turnaroundPath -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($turnaround.hard_gate_failures.Count -ne 0 -or $turnaround.single_body_edit.p95_ms -ge 1000.0) { throw 'original editing P95 gate failed' }
    if ($turnaround.frontend_transient_target_met -ne $true -or $turnaround.worker_private_bytes_target_met -ne $true) { throw 'original editing memory gate failed' }
    Assert-MissingPeakControl
}

function Invoke-Benchmark {
    $raw = Join-Path $root 'docs/plans/attachments/825/bench-r6'
    New-Item -ItemType Directory -Force -Path $raw | Out-Null
    foreach ($name in @('av.jsonl', 'js.jsonl', 'liftoff.jsonl', 'turbofan.jsonl', 'summary.json', 'js-tier.log', 'liftoff-tier.log', 'turbofan-tier.log', 'turnaround.jsonl', 'turnaround-summary.json')) {
        if (Test-Path (Join-Path $raw $name)) { Remove-Item -LiteralPath (Join-Path $raw $name) -Force }
    }
    Invoke-Cargo -CargoArgs @('build', '--release', '--manifest-path', 'experimental/ac-av-probe/Cargo.toml', '--bin', 'av_runtime_825_bench', '--bin', 'av_probe_worker') | Out-Host
    Invoke-Native -Exe (Join-Path $probe 'target/release/av_runtime_825_bench.exe') -NativeArgs @('--out', (Join-Path $raw 'av.jsonl')) -Log (Join-Path $raw 'av-tier.log')
    Invoke-Native -Exe 'node' -NativeArgs @('--jitless', '--print-bytecode', 'scripts/av-825-bench.mjs', '--engine', 'v8-js-ignition', '--out', (Join-Path $raw 'js.jsonl')) -Log (Join-Path $raw 'js-tier.log')
    Invoke-Native -Exe 'node' -NativeArgs @('--liftoff-only', '--no-wasm-tier-up', '--no-wasm-dynamic-tiering', '--trace-wasm-compilation-times', 'scripts/av-825-bench.mjs', '--engine', 'v8-wasm-liftoff', '--out', (Join-Path $raw 'liftoff.jsonl')) -Log (Join-Path $raw 'liftoff-tier.log')
    Invoke-Native -Exe 'node' -NativeArgs @('--no-liftoff', '--trace-wasm-compilation-times', 'scripts/av-825-bench.mjs', '--engine', 'v8-wasm-turbofan', '--out', (Join-Path $raw 'turbofan.jsonl')) -Log (Join-Path $raw 'turbofan-tier.log')
    & powershell -NoProfile -File (Join-Path $root 'scripts/av-825-bench-report.ps1') -RawDir $raw -OutFile (Join-Path $raw 'summary.json')
    if ($LASTEXITCODE -ne 0) { throw 'benchmark report failed' }
    Assert-TierEvidence -JsLog (Join-Path $raw 'js-tier.log') -LiftoffLog (Join-Path $raw 'liftoff-tier.log') -TurboLog (Join-Path $raw 'turbofan-tier.log')
    $summary = Get-Content -LiteralPath (Join-Path $raw 'summary.json') -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($summary.total_rows -ne 1720 -or $summary.groups.Count -ne 40) { throw 'benchmark group/row completeness mismatch' }

    Invoke-Native -Exe (Join-Path $probe 'target/release/av_probe_worker.exe') -NativeArgs @('bench-turnaround', '--samples', '30', '--gate-ms', '1000', '--out', (Join-Path $raw 'turnaround.jsonl')) -Log (Join-Path $raw 'turnaround-summary.json')
    $turnaround = Get-Content -LiteralPath (Join-Path $raw 'turnaround-summary.json') -Raw -Encoding UTF8 | ConvertFrom-Json
    if ($turnaround.hard_gate_failures.Count -ne 0 -or $turnaround.single_body_edit.p95_ms -ge 1000.0) { throw 'original editing P95 gate failed' }
    if ($turnaround.frontend_transient_target_met -ne $true -or $turnaround.worker_private_bytes_target_met -ne $true) { throw 'original editing memory gate failed' }

    Assert-MissingPeakControl
}

function Run-Probe {
    param([string]$Bin, [string]$Filter = '', [string[]]$RequiredIds)
    Push-Location $probe
    try {
        $args = @('test', '-p', 'auto-av-probe', '--test', $Bin)
        if ($Filter) { $args += $Filter }
        $out = Invoke-Cargo -CargoArgs $args
        Assert-Selected -Output $out -Label $Bin -RequiredIds $RequiredIds
    } finally { Pop-Location }
}

function Run-Runner {
    param([string]$Filter, [string[]]$RequiredIds)
    Push-Location $root
    try {
        $out = Invoke-Cargo -CargoArgs @('test', '-p', 'auto-lang', '--lib', '--features', 'auto-lang/test-cases', $Filter, '--', '--test-threads=1')
        Assert-Selected -Output $out -Label $Filter -RequiredIds $RequiredIds
    } finally { Pop-Location }
}

if ($GuardSelfTest) {
    $valid = "running 2 tests`ntest alpha ... ok`ntest beta ... ok`n`ntest result: ok. 2 passed; 0 failed; 0 ignored; 0 measured; 0 filtered out"
    Assert-Selected -Output $valid -Label 'valid' -RequiredIds @('alpha', 'beta')
    $long = "running 1 test`ntest alpha has been running for over 60 seconds`ntest alpha ... ok`n`ntest result: ok. 1 passed; 0 failed; 0 ignored; 0 measured; 0 filtered out"
    Assert-Selected -Output $long -Label 'long-result' -RequiredIds @('alpha')
    foreach ($case in @(
        @{ Name = 'skip'; Out = "running 1 test`ntest alpha ... ignored`n`ntest result: ok. 0 passed; 0 failed; 1 ignored; 0 measured; 0 filtered out"; Req = @('alpha') },
        @{ Name = 'missing'; Out = $valid; Req = @('alpha', 'gamma') },
        @{ Name = 'zero'; Out = 'test result: ok. 0 passed; 0 failed; 0 ignored; 0 measured; 3 filtered out'; Req = @() },
        @{ Name = 'duplicate'; Out = "running 3 tests`ntest alpha ... ok`ntest alpha ... ok`ntest beta ... ok`n`ntest result: ok. 3 passed; 0 failed; 0 ignored; 0 measured; 0 filtered out"; Req = @('alpha', 'beta') }
    )) {
        $rejected = $false
        try { Assert-Selected -Output $case.Out -Label $case.Name -RequiredIds $case.Req } catch { $rejected = $true }
        if (-not $rejected) { throw "$($case.Name) counter-control was accepted" }
    }
    $dir = Join-Path ([IO.Path]::GetTempPath()) "av825-guard-$PID"
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    Set-Content -LiteralPath (Join-Path $dir 'js.log') -Value '[generated bytecode for function: main' -Encoding UTF8
    Set-Content -LiteralPath (Join-Path $dir 'liftoff.log') -Value (@('using Liftoff' * 8) -join "`n") -Encoding UTF8
    Set-Content -LiteralPath (Join-Path $dir 'turbo.log') -Value (@('using TurboFan' * 8) -join "`n") -Encoding UTF8
    Assert-TierEvidence -JsLog (Join-Path $dir 'js.log') -LiftoffLog (Join-Path $dir 'liftoff.log') -TurboLog (Join-Path $dir 'turbo.log')
    Set-Content -LiteralPath (Join-Path $dir 'liftoff.log') -Value (@('using TurboFan' * 8) -join "`n") -Encoding UTF8
    $rejected = $false
    try { Assert-TierEvidence -JsLog (Join-Path $dir 'js.log') -LiftoffLog (Join-Path $dir 'liftoff.log') -TurboLog (Join-Path $dir 'turbo.log') } catch { $rejected = $true }
    Remove-Item -LiteralPath $dir -Recurse -Force
    if (-not $rejected) { throw 'fake-tier counter-control was accepted' }
    Write-Host 'GuardSelfTest: valid, long-result, skip, missing, zero, duplicate and fake-tier controls behave'
    exit 0
}

