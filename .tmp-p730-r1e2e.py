    '        for chunk in payload.chunks(64 * 1024) {\n'
    '            let frame = format!("{:x}{BS}r{BS}n", chunk.len());\n'
    '            stream.write_all(frame.as_bytes()).unwrap();\n'
    '            stream.write_all(chunk).unwrap();\n'
    '            stream.write_all(b"{BS}r{BS}n").unwrap();\n'
    '        }\n'
    '        stream.write_all(b"0{BS}r{BS}n{BS}r{BS}n").unwrap();\n'
    '        let (status, _h, b) = read_response(&mut stream);\n'
    '        assert_eq!(status, 201, "{}", String::from_utf8_lossy(&b));\n'
