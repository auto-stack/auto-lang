    '        let mut holder = connect(port);\n'
    '        holder.set_read_timeout(Some(Duration::from_secs(60))).ok();\n'
    '        let head = "POST /api/uploads/raw HTTP/1.1{BS}r{BS}nHost: x{BS}r{BS}nConnection: close{BS}r{BS}nContent-Type: application/octet-stream{BS}r{BS}nContent-Length: 1048576{BS}r{BS}n{BS}r{BS}n";\n'
