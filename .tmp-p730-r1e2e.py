    '    /// 20 次 health 独立连接均 <500ms（owner 不被接收阻塞）。\n'
    '    #[test]\n'
    '    fn http_e2e_plan730_vm_quota_and_health_under_load() {\n'
    '        std::env::set_var("AUTO_HTTP_UPLOAD_ACTIVE", "1");\n'
    '        std::env::set_var("AUTO_HTTP_UPLOAD_QUEUE", "1");\n'
    '        std::env::set_var("AUTO_HTTP_UPLOAD_QUEUE_TIMEOUT_MS", "600");\n'
    '        let (root, staging) = temp_roots("quota");\n'
